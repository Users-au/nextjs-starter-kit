import { createApplicationContextUrl, createPushedAuthorizationUrl } from '@users-au/client/server'
import { authEnvironment, type AuthEnvironment } from './auth-config'
import { authPaths } from './auth-paths'

export function applicationContext(env: AuthEnvironment) {
  const { appOrigin } = authEnvironment(env)
  return {
    context_id: env.USERSAU_CONTEXT_ID || appOrigin,
    branding: {
      name: env.NEXT_PUBLIC_APP_NAME || 'Users.au starter',
      ...(env.USERSAU_LOGO_URL ? { logo_url: env.USERSAU_LOGO_URL } : {}),
      ...(env.USERSAU_LOGO_DARK_URL ? { logo_dark_url: env.USERSAU_LOGO_DARK_URL } : {}),
      ...(env.USERSAU_FAVICON_URL ? { favicon_url: env.USERSAU_FAVICON_URL } : {}),
    },
    links: { home_url: `${appOrigin}/`, logout_url: `${appOrigin}/auth/login` },
  }
}

export function applicationContextUrl(env: AuthEnvironment, purpose: 'account' | 'logout') {
  const config = authEnvironment(env)
  return createApplicationContextUrl({ host: config.identityOrigin, clientId: config.clientId, clientSecret: config.clientSecret }, purpose, applicationContext(env))
}

/** Push the URL generated by NextAuth after it sets its state/PKCE cookies. Keep those cookies unchanged. */
export async function pushAuthorizationResponse(response: Response, env: AuthEnvironment): Promise<Response> {
  const config = authEnvironment(env)
  let target = response.headers.get('location')
  let json = false
  if (!target && response.headers.get('content-type')?.includes('application/json')) {
    const data: unknown = await response.clone().json()
    if (data && typeof data === 'object' && 'url' in data && typeof data.url === 'string') { target = data.url; json = true }
  }
  if (!target) return response
  const url = new URL(target, config.appOrigin)
  if (url.origin !== config.identityOrigin || url.pathname !== '/oauth/authorize') return response
  const params = url.searchParams
  const redirect = `${config.appOrigin}${authPaths.callback}`
  if (params.get('redirect_uri') !== redirect || params.get('response_type') !== 'code' || params.get('client_id') !== config.clientId ||
      params.get('code_challenge_method') !== 'S256' || !/^[A-Za-z0-9_-]{43}$/.test(params.get('code_challenge') || '') ||
      (params.get('state') || '').length < 20) throw new Error('Invalid Users.au authorization request.')
  const pushed = await createPushedAuthorizationUrl({ host: config.identityOrigin, clientId: config.clientId, clientSecret: config.clientSecret }, {
    redirect_uri: redirect, scope: config.scope, state: params.get('state')!, code_challenge: params.get('code_challenge')!,
  }, applicationContext(env))
  const headers = new Headers(response.headers)
  headers.delete('content-length')
  headers.set('cache-control', 'no-store')
  headers.set('referrer-policy', 'no-referrer')
  if (json) return Response.json({ url: pushed }, { status: response.status, headers })
  headers.set('location', pushed)
  return new Response(null, { status: response.status, headers })
}
